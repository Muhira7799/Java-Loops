
class Main {
    public static void main(String[] args) {

        // 1. While Loop
        System.out.println("While Loop:");
        int i = 1;

        while (i <= 5) {
            System.out.println(i);
            i++;
        }

        // 2. Do-While Loop
        System.out.println("Do-While Loop:");
        int j = 1;

        do {
            System.out.println(j);
            j++;
        } while (j <= 5);

        // 3. For Loop
        System.out.println("For Loop:");

        for (int k = 1; k <= 5; k++) {
            System.out.println(k);
        }
    }
}
